// Emit G-code from toolpaths. Relative extrusion (M83), volumetric E.
//
// The output is a pure function of (toolpaths, settings, provenance): no
// timestamps, so slicing the same inputs twice gives the same bytes and the
// job keeps its G-code file doc (see output.js).

import { SCALE } from "./slice.js";
import { filamentDensity, stableStringify } from "./settings.js";

export const GENERATOR = "Patchwork Slicer 3";

const f = (v, n = 3) => +v.toFixed(n);

/** Strip anything that would end a G-code comment early. */
const clean = (v) => String(v ?? "").replace(/[\r\n]+/g, " ");

/**
 * Comment lines saying where this G-code came from.
 * @param {object} p
 * @param {string} [p.job]         the slice-job url
 * @param {string} p.source        the source url (a scene render or a file)
 * @param {"scene-render"|"glb"|"stl"} p.sourceKind
 * @param {string} p.sourceKey     renderKey for a render, the content hash for a file
 * @param {string} [p.renderOf]    the render's own source doc (what the scene object is)
 * @param {string} [p.unit], [p.unitSource], [p.scale]
 * @param {object} p.settings      the effective settings
 */
export function provenanceHeader(p) {
  const out = [`; generated by ${GENERATOR}`];
  if (p.job) out.push(`; job = ${clean(p.job)}`);
  out.push(`; source = ${clean(p.source)}`);
  out.push(`; source_kind = ${clean(p.sourceKind)}`);
  out.push(`; source_key = ${clean(p.sourceKey)}`);
  if (p.renderOf) out.push(`; render_of = ${clean(p.renderOf)}`);
  if (p.unit) out.push(`; units = ${clean(p.unit)} (${clean(p.unitSource ?? "")})`);
  if (p.scale != null) out.push(`; scale = ${clean(p.scale)}`);
  out.push(`; settings = ${clean(stableStringify(p.settings ?? {}))}`);
  return out;
}

/**
 * Read the provenance back out of G-code text (the first comment block).
 * @returns {{ [key]: string }}  e.g. { source, source_kind, source_key, settings, ... }
 */
export function readProvenance(text) {
  const out = {};
  for (const line of String(text).split("\n", 40)) {
    const m = /^; ([a-z_]+) = (.*)$/.exec(line);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

export function generateGcode(toolpaths, s, provenance = null) {
  const out = [];
  const area = Math.PI * (s.filamentDiameter / 2) ** 2;
  let x = 0, y = 0, z = 0, retracted = false;
  let totalE = 0, time = 0;
  const eFor = (len, h) => (len * s.lineWidth * h * s.flow) / area;
  const P = (p) => [p.X / SCALE, p.Y / SCALE];

  if (provenance) out.push(...provenanceHeader({ ...provenance, settings: provenance.settings ?? s }));
  else out.push(`; generated by ${GENERATOR}`);
  out.push(`; layer_height = ${s.layerHeight}  first_layer_height = ${s.firstLayerHeight}  walls = ${s.wallLoops}  infill = ${s.infillDensity}%  filament = ${s.filament}`);
  if (s.supports) out.push("; supports were requested but are not generated by this slicer");
  const statsAt = out.length;
  out.push("M83 ; relative extrusion");
  out.push(`M140 S${s.bedTemp}`);
  out.push(`M104 S${s.nozzleTemp}`);
  out.push("G28 ; home");
  out.push(`M190 S${s.bedTemp}`);
  out.push(`M109 S${s.nozzleTemp}`);
  out.push("G90");

  const travel = (nx, ny, nz) => {
    const d = Math.hypot(nx - x, ny - y);
    if (d < 0.01 && nz === undefined) return;
    if (!retracted && d > 1.5) {
      out.push(`G1 E${-s.retract} F${s.retractSpeed * 60}`);
      retracted = true;
    }
    if (nz !== undefined && nz !== z) {
      out.push(`G1 Z${f(nz)} F${600}`);
      z = nz;
    }
    out.push(`G0 X${f(nx, 2)} Y${f(ny, 2)} F${s.travelSpeed * 60}`);
    time += d / s.travelSpeed;
    x = nx;
    y = ny;
  };
  const unretract = () => {
    if (retracted) {
      out.push(`G1 E${s.retract} F${s.retractSpeed * 60}`);
      retracted = false;
    }
  };
  const line = (nx, ny, h, speed) => {
    const d = Math.hypot(nx - x, ny - y);
    if (d < 0.001) return;
    const e = eFor(d, h);
    out.push(`G1 X${f(nx, 2)} Y${f(ny, 2)} E${f(e, 4)} F${speed * 60}`);
    totalE += e;
    time += d / speed;
    x = nx;
    y = ny;
  };
  const poly = (pts, closed, h, speed) => {
    const p = pts.map(P);
    travel(p[0][0], p[0][1]);
    unretract();
    for (let i = 1; i < p.length; i++) line(p[i][0], p[i][1], h, speed);
    if (closed) line(p[0][0], p[0][1], h, speed);
  };

  toolpaths.layers.forEach((L, i) => {
    out.push(`;LAYER:${i}`);
    out.push(`;Z:${f(L.z)}`);
    travel(x, y, L.z);
    if (i === 1 && s.fanSpeed > 0) out.push(`M106 S${Math.round((s.fanSpeed / 100) * 255)}`);
    const first = i === 0;
    const sp = (v) => (first ? s.firstLayerSpeed : v);
    out.push(";TYPE:WALL");
    // outer wall last for quality: print inner rings first
    for (let k = L.rings.length - 1; k >= 0; k--) for (const r of L.rings[k]) if (r.length > 2) poly(r, true, L.h, sp(s.wallSpeed));
    out.push(";TYPE:SOLID");
    for (const l of L.solid) poly(l, false, L.h, sp(s.infillSpeed * 0.6));
    out.push(";TYPE:INFILL");
    for (const l of L.sparse) poly(l, false, L.h, sp(s.infillSpeed));
  });

  out.push("; end");
  out.push(`G1 E${-s.retract} F${s.retractSpeed * 60}`);
  out.push(`G1 Z${f(Math.min(z + 10, s.bedZ))} F600`);
  out.push("M107");
  out.push("M104 S0");
  out.push("M140 S0");
  out.push("M84");
  const filamentMm = totalE;
  const grams = (filamentMm * area * filamentDensity(s.filament)) / 1000;
  out.splice(statsAt, 0, `; estimated time = ${Math.round(time)} s`, `; filament used = ${f(filamentMm / 1000, 2)} m (${f(grams, 1)} g ${s.filament})`);
  return { gcode: out.join("\n") + "\n", time, filamentMm, grams, lines: out.length };
}
