// Writes src/generated/toolkit.js: ink-studio's browser toolkit as one ES
// module, made by upstream's own bundle() from the vendored checkout, with its
// seven built-in demo dioramas appended (they push onto SCENES).
//
// Upstream's sources are plain scripts meant to be concatenated into a page;
// bundle({ format: "module" }) is their supported way to import them.

import { createRequire } from "node:module";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const studio = require(join(here, "../vendor/ink-studio/index.js"));

const scripts = studio.bundle(); // classic-script form, so we can append the demos before exporting
const text = [
  "// GENERATED by scripts/toolkit.mjs from vendor/ink-studio. Do not edit.",
  "/* eslint-disable */",
  scripts,
  "const SCENES = [];",
  studio.demos(),
  `export { ${studio.EXPORTS}, SCENES };`,
  `export const VERSION = ${JSON.stringify(studio.version)};`,
  "",
].join("\n");

const out = join(here, "../src/generated/toolkit.js");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, text);
console.log(`toolkit: ${(text.length / 1e6).toFixed(1)} MB -> ${out}`);
