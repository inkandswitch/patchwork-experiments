#!/usr/bin/env node
/**
 * Writes tools/vendor/vitest-engine.js: vitest's own engine as one ES module.
 *
 * package_test runs tests in a page or a worker inside Patchwork, where there
 * is no vitest CLI and may be no network. What decides what a test means —
 * collection, hooks, timeouts, only/skip/each, the matchers, vi.fn — lives in
 * @vitest/runner, @vitest/expect, @vitest/spy and chai, and none of those need
 * Node. So they are bundled here at the exact version the package's own
 * `vitest run` uses, and the same file is what a page, a worker and this
 * package's tests import.
 *
 *   pnpm vendor:vitest
 *
 * Rerun it when vitest is upgraded; the test in testing.test.js fails when
 * the two versions differ.
 */

import { build } from "esbuild"
import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, "..")
const require = createRequire(join(root, "package.json"))
const versionOf = (name) => JSON.parse(readFileSync(require.resolve(`${name}/package.json`), "utf8")).version

const versions = {
  "@vitest/runner": versionOf("@vitest/runner"),
  "@vitest/expect": versionOf("@vitest/expect"),
  "@vitest/spy": versionOf("@vitest/spy"),
  chai: versionOf("chai"),
}

const entry = `
export * as runner from "@vitest/runner"
export * as expect from "@vitest/expect"
export * as spy from "@vitest/spy"
export * as chai from "chai"
export const versions = ${JSON.stringify(versions)}
`

// vitest's value printer reads process.env and process.cwd(); a page and a
// worker have no process, Node has the real one.
const banner = `/* GENERATED by scripts/vendor-vitest.mjs from ${Object.entries(versions).map(([n, v]) => `${n}@${v}`).join(", ")}. Do not edit. */
const process = globalThis.process ?? { env: { NODE_ENV: "production" }, cwd: () => "/", platform: "browser", versions: {}, argv: [] };`

const result = await build({
  stdin: { contents: entry, resolveDir: root, loader: "js" },
  bundle: true,
  format: "esm",
  platform: "neutral",
  conditions: ["browser", "import"],
  mainFields: ["module", "main"],
  target: "es2022",
  banner: { js: banner },
  write: false,
  logLevel: "silent",
  metafile: true,
})

const nodeImports = Object.values(result.metafile.inputs)
  .flatMap((input) => input.imports)
  .filter((i) => i.external)
  .map((i) => i.path)
if (nodeImports.length) {
  console.error(`the engine would import ${[...new Set(nodeImports)].join(", ")}, which a page cannot`)
  process.exit(1)
}

const out = join(root, "tools", "vendor", "vitest-engine.js")
mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, result.outputFiles[0].text)
console.log(`wrote ${out} (${Math.round(result.outputFiles[0].contents.length / 1024)} KB)`)
