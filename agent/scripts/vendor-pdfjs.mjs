#!/usr/bin/env node
/**
 * Writes tools/vendor/pdfjs.js: pdf.js (parser and worker together) as one ES
 * module, so the agent reads a PDF's text itself, in a page, a worker or node,
 * with no reader service and no network.
 *
 * The worker is imported into the same bundle and registered as
 * `globalThis.pdfjsWorker`, which is where pdf.js looks before it tries to
 * start a Worker from a URL: it then parses on the calling thread, which is
 * what a tool already running in a worker wants and a page can afford for a
 * datasheet.
 *
 *   pnpm vendor:pdfjs
 *
 * Rerun it when pdfjs-dist is upgraded.
 */

import { build } from "esbuild"
import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, "..")
const require = createRequire(join(root, "package.json"))
const version = JSON.parse(readFileSync(require.resolve("pdfjs-dist/package.json"), "utf8")).version

const entry = `
import * as pdfjs from "pdfjs-dist/legacy/build/pdf.min.mjs"
import { WorkerMessageHandler } from "pdfjs-dist/legacy/build/pdf.worker.min.mjs"
globalThis.pdfjsWorker = { WorkerMessageHandler }
export const getDocument = pdfjs.getDocument
export const version = ${JSON.stringify(version)}
`

const result = await build({
  stdin: { contents: entry, resolveDir: root, loader: "js" },
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  banner: { js: `/* GENERATED by scripts/vendor-pdfjs.mjs from pdfjs-dist@${version}. Do not edit. */` },
  minify: true,
  write: false,
  logLevel: "silent",
  metafile: true,
})

const external = Object.values(result.metafile.inputs).flatMap((input) => input.imports).filter((i) => i.external).map((i) => i.path)
if (external.length) {
  console.error(`pdf.js would import ${[...new Set(external)].join(", ")}, which a page cannot`)
  process.exit(1)
}

const out = join(root, "tools", "vendor", "pdfjs.js")
mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, result.outputFiles[0].text)
console.log(`wrote ${out} (${Math.round(result.outputFiles[0].contents.length / 1024)} KB)`)
